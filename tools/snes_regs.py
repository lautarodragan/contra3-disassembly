_DMA = ['DMAP', 'BBAD', 'A1T%dL', 'A1T%dH', 'A1B', 'DAS%dL', 'DAS%dH', 'DASB',
        'A2A%dL', 'A2A%dH', 'NLTR']

NAMES = dict(_BASE)
for _ch in range(8):
    for _i, _n in enumerate(_DMA):
        NAMES[0x4300 + _ch * 0x10 + _i] = (_n % _ch) if '%' in _n else '%s%d' % (_n, _ch)


def write_inc(path):
    with open(path, 'w') as f:
        f.write('; SNES hardware registers.  Generated by tools/snes_regs.py.\n\n')
        for a in sorted(NAMES):
            f.write('%-10s = $%04X\n' % (NAMES[a], a))
