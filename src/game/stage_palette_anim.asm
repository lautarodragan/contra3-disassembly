; A = palette animation (x2): stored in palette_anim_id, restarts the timer.
start_palette_anim:
	sta	a:palette_anim_id
	stz	a:palette_anim_timer
	rtl

; Applies the first palette of palette_anim_id once and stops the animation.
apply_palette_anim_once:
	ldy	a:palette_anim_id
	stz	a:palette_anim_id
	bra	palette_anim_apply_first

